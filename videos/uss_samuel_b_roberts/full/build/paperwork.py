"""MANIFEST.md + CREDITS.md for the USS Samuel B. Roberts final cut, generated from footage/footage.json (rights read on each record page by the
footage agent) and build/segments.json (only what the shot lists put on screen). Photo crops (*_c, aer_*, aerial_1936_*, *_L/_R) are
credited to their source item."""
import json, os, re, collections
HERE = os.path.dirname(os.path.abspath(__file__)); FULL = os.path.dirname(HERE); ROOT = os.path.abspath(os.path.join(FULL, "../../.."))
FT = json.load(open(os.path.join(ROOT, "videos/uss_samuel_b_roberts/footage/footage.json")))
PH = {p["stem"]: p for p in FT["photos"]}; FI = {f["stem"]: f for f in FT["films"]}
SEG = json.load(open(os.path.join(HERE, "segments.json")))
FW = json.load(open(os.path.join(HERE, "film_windows.json")))
CROP = {}
def src_of(stem):
    for pre, s in CROP.items():
        if stem.startswith(pre):
            if stem in ("aer_creek", "aer_shore", "aer_isl_a", "aer_river"): return "naip_mallows_bay_008"
            if stem in ("aer_shore2", "aer_ferry", "aer_creek2"): return "usgs_mallows_tight"
            if stem == "aer_isl_b": return "usgs_mallows_close"
            if stem == "aer_park": return "naip_mallows_mid_020"
            return s
    s = re.sub(r"(_c|_L|_R)$", "", stem)
    return s
cell = lambda x: str(x or "").replace("|", "/").replace("\n", " ")
# ---- MANIFEST (film)
M = ["# MANIFEST: archive film on screen in the final cut (generated by build/paperwork.py; do not edit by hand)", "",
     "Video: `videos/uss_samuel_b_roberts/full/uss_samuel_b_roberts_full_v1.mp4`. One row per film segment the shot lists put on screen. In/out = seconds in the "
     "source reel. Every film shot carries an on-screen tag saying what it is; shots that are not the Samuel B. Roberts or not this event are tagged "
     "ILLUSTRATIVE or named. **No 2022 wreck imagery (Caladan Oceanic, copyrighted) is shown.** No film of the Samuel B. Roberts herself exists in the sources: battle film shows other Leyte Gulf ships. "
     "NARA 'Undetermined' = US Navy film, federal work; NOAA Ocean Exploration video = US Government work, public domain (ILLUSTRATIVE deep sea, not the wreck site).", "",
     "| clip | chapter | source reel | in/out (reel s) | on-screen tag | what the reel shows here | what it does NOT show | rights |", "|---|---|---|---|---|---|---|---|"]
for s in SEG:
    if s["kind"] != "film": continue
    f = FI.get(s["reel"], {}); a = s["reel_in"]; b = round(a + s["dur"], 2)
    sh = next((x for x in (f.get("shots") or f.get("windows") or []) if x["in"] - 1 <= a <= x["out"] + 1), {})
    M.append(f"| {s['file']} | {s['chapter']} | {cell(f.get('title'))} ({cell(f.get('url'))}) | {a}-{b} | {cell(FW[s['clip']]['tag'])} | {cell(sh.get('shows'))} | {cell(sh.get('not_shows'))} | {cell(f.get('rights'))[:160]} |")
open(os.path.join(FULL, "MANIFEST.md"), "w").write("\n".join(M) + "\n")
# ---- CREDITS
used_p = collections.OrderedDict(); used_f = collections.OrderedDict()
for s in SEG:
    if s["kind"] == "photo": used_p.setdefault(src_of(s["photo"]), []).append(s["photo"])
    if s["kind"] == "film": used_f.setdefault(s["reel"], []).append(s["file"])
C = ["# Credits: final cut (generated by build/paperwork.py from footage/footage.json; only items on screen)", "",
     "## Archive photos and modern imagery", "", "| item | what | date | rights (as read on the record page) | record | crops used |", "|---|---|---|---|---|---|"]
miss = []
for st, crops in used_p.items():
    p = PH.get(st)
    if not p: miss.append(st); continue
    C.append(f"| {st} | {cell(p.get('title') or p.get('shows'))[:120]} | {cell(p.get('date'))} | {cell(p.get('rights'))[:180]} | {cell(p.get('url'))} | {', '.join(sorted(set(crops)))} |")
C += ["", "## Archive film", "", "| reel | title | rights | record |", "|---|---|---|---|"]
for st in used_f:
    f = FI.get(st, {}); C.append(f"| {st} | {cell(f.get('title'))} | {cell(f.get('rights'))[:180]} | {cell(f.get('url'))} |")
if miss: C += ["", "**Not in footage.json (check):** " + ", ".join(miss)]
C += ["", "## Music",
      "- \"Stories About the World That Once Was\", \"That Hopeful Future Is All I've Ever Known\", \"Your Mother's Daughter\", \"To Hide Their Secrets\" and \"I Should Have Been More Human\" by Chris Zabriskie, from the album Music from Neptune Flux. Licensed under Creative Commons Attribution 4.0.",
      "", "## Sound effects", "- Sound effects from Epidemic Sound (owner's subscription; files not redistributed). Roles and IDs: assets/sfx/EPIDEMIC_SFX.md.",
      "", "## Narration", "- AI voice: Kokoro TTS v1.0 (Apache 2.0), designed voice Archive (style blend bm_fable 0.40 + am_michael 0.40 + bm_lewis 0.20, speed 0.92). Disclose as altered / synthetic content on YouTube (box ticked: Yes).",
      "", "## Maps and graphics",
      "- Terrain and bathymetry: Mapzen / AWS Terrain Tiles (open data); deep-ocean colour ramp made for this video.",
      "- Photo depth moves: Depth Anything V2 Small (Apache 2.0).",
      "- Approximate on the maps (labelled APPROX.): every ship position in the battle, Kurita's route, the Houston-Samar line (schematic), the wreck site, the Johnston and Gambier Bay markers, the FFG-58 mine strike. The exact wreck position is not public."]
open(os.path.join(FULL, "CREDITS.md"), "w").write("\n".join(C) + "\n")
print("MANIFEST", len(M) - 6, "film rows; CREDITS", len(used_p), "photo items,", len(used_f), "reels; missing:", miss)
