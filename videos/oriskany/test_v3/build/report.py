"""Writes SOUND_REPORT.md: cue table (from build/sfx_placed.json), levels, ducking, measured loudness, and the
video-vs-still-vs-animation screen time from the chapter timeline."""
import json, os, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); V = os.path.join(HERE, "..")
W = json.load(open(os.path.join(HERE, "words.json"))); W = W["words"] if isinstance(W, dict) else W
CH = json.load(open(os.path.join(V, "chapter/c01.json"))); T = float(CH["duration"])
def st(s): return float(s) if isinstance(s, (int, float)) else (float(s[1:]) if s[0] == "t" else W[int(s[1:])]["start"])
shots = CH["shots"]; starts = [st(s["start"]) for s in shots]; ends = starts[1:] + [T]
KIND = {"video": "real film (moving)", "board": "graphic over moving film", "still": "real photo (still, with motion)", "anim": "animation / map"}
def kind(s):
    if s.get("bg_clip"): return "board"
    f = (s.get("clip") or {}).get("file", "")
    if f.startswith("f"): return "video"
    if s["template"] in ("anim_xray", "anim_options") or f in ("dive.mp4", "hero.mp4", "endmap.mp4"): return "anim"
    return "still"
rows, tot = [], {k: 0.0 for k in KIND}
for s, a, b in zip(shots, starts, ends):
    k = kind(s); tot[k] += b - a; rows.append((a, b, s["id"], k, (s.get("clip") or {}).get("file", s["template"])))
def meas(p):
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", p, "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True).stderr
    s = r[r.rindex("Summary:"):]; return float(s.split("I:")[1].split()[0]), float(s.split("LRA:")[1].split()[0]), float(s.split("Peak:")[1].split()[0])
I, LRA, TP = meas(os.path.join(V, "oriskany_test_v3.mp4")); vI = meas(os.path.join(V, "audio/voice.wav"))[0]; sI = meas(os.path.join(V, "audio/sfx.wav"))[0]
placed = json.load(open(os.path.join(HERE, "sfx_placed.json")))
L = ["# Oriskany test v3: sound report", "",
     "Rules applied: battle-maps STYLE_LOCK sections 3 / 3a / 5 / 2c-5 / 2c-9 through the ported tools in `tools/sound/` "
     "(`sfx_mix_lib.py` roles + levels + min gaps, `check_sound_lock.py`, `make_music_bed.py`, `mix_clip.py`). "
     "Sounds = the channel's own kit (`kit/ship/sfx/out`), mapped to the locked roles. No risers, drones, pops or projector loops (2c-5).", "",
     "## Mix chain (locked, STYLE_LOCK 5)", "",
     "| Stage | Setting |", "|---|---|",
     "| Music bed | Chris Zabriskie \"Stories About the World That Once Was\" (CC BY 4.0), fitted to 53.6 s, loudnorm -20 LUFS, 3 s fade-out (`make_music_bed.py`) |",
     "| Music level | `volume=0.08` (MUSIC_VOL), 2 s fade-in, 3 s fade-out; bed at 0.08 measures -40.8 LUFS before ducking |",
     "| Music ducking | sidechain on the voice: threshold 0.03, ratio 6, attack 20 ms, release 400 ms |",
     "| SFX | FULL level (no overall cut), role levels below; ducked lightly: threshold 0.03, ratio 3, attack 10 ms, release 300 ms |",
     "| Master | amix normalize=0, alimiter 0.5, two-pass loudnorm I -14 / TP -1.5 / LRA 11 (linear), then the 2c-9 measured trim + limiter; AAC 192k |",
     f"| Stems (integrated) | voice {vI:.1f} LUFS, SFX stem {sI:.1f} LUFS |",
     f"| **Final** | **{I:.1f} LUFS integrated, true peak {TP:.1f} dBTP, LRA {LRA:.1f} LU** |", "",
     "## Cues (every cue is generated by `build/sfx_cues.py` from the word timings and shot starts)", "",
     "| t (s) | role | level dB (locked + jitter) | sound | on screen |", "|---|---|---|---|---|"]
L += [f"| {p[0]:.2f} | {p[1]} | {p[3]:.1f} | {p[2]} | {p[4]} |" for p in placed]
L += ["", f"{len(placed)} cues in {T:.1f} s = {len(placed) / T * 60:.1f} per minute (bursts on the hook and the reveals; 31-40 s is quiet).", "",
      "Role levels (battle-maps locked table): explosion -4, impact -7, hit/slam -8, jet -11, whoosh -12 (only the 2 biggest camera moves), ship sound on screen -13, tick -20. "
      "Not used, on purpose: labels and lower thirds are silent (battle-maps: badges slide in silently); no sound for the parked A-4 (aircraft sound only when it flies).", "",
      "## Screen time", "", "| type | seconds | share |", "|---|---|---|"]
L += [f"| {KIND[k]} | {v:.1f} | {v / T * 100:.0f}% |" for k, v in tot.items()]
L += ["", f"Moving real footage incl. the board over film: **{(tot['video'] + tot['board']) / T * 100:.0f}%**; stills **{tot['still'] / T * 100:.0f}%** (all 2006 photos: there is no public-domain video of the 2006 prep, tow or sinking); animation/maps **{tot['anim'] / T * 100:.0f}%**.", "",
      "| from | to | shot | type | source |", "|---|---|---|---|---|"]
L += [f"| {a:.2f} | {b:.2f} | {i} | {k} | {f} |" for a, b, i, k, f in rows]
open(os.path.join(V, "SOUND_REPORT.md"), "w").write("\n".join(L) + "\n")
print({k: round(v / T * 100, 1) for k, v in tot.items()}, I, TP, LRA)
