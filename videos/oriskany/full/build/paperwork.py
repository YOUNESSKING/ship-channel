"""MANIFEST.md + CREDITS.md for the FINAL cut (step 3). tools/film/make_paperwork.py run twice and merged:
  - on full/ (chapters c02-c07: build/films.py + build/shots.py cut lists),
  - on test_v4/ (the hook c01 is the approved test v4 chapter, its clips come from test_v4/segments + test_v4 cut lists),
then the non-archive sections (music, sound effects, narration, maps and graphics, illustrative notes) are written here.
Only files that the final shot lists put on screen are listed (the generator reads chapter/*.json)."""
import os, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); FULL = os.path.dirname(HERE); ROOT = os.path.abspath(os.path.join(FULL, "../../.."))
V4 = os.path.join(ROOT, "videos/oriskany/test_v4"); GEN = os.path.join(ROOT, "tools/film/make_paperwork.py")
tmp = tempfile.mkdtemp()
# generator keeps "## Music/Sound/Narration/Maps" sections of an existing CREDITS.md: start each run from an empty one
run = lambda vdir, m, c: subprocess.run([sys.executable, GEN, vdir, "--out-manifest", m, "--out-credits", c], check=True,
                                        cwd=ROOT, env=dict(os.environ))
fm, fc, hm, hc = (os.path.join(tmp, x) for x in ("fm.md", "fc.md", "hm.md", "hc.md"))
cred = os.path.join(FULL, "CREDITS.md")
saved = open(cred).read() if os.path.exists(cred) else None
try:
    if os.path.exists(cred): os.remove(cred)
    run(FULL, fm, fc)
finally:
    if saved is not None and not os.path.exists(cred): open(cred, "w").write(saved)
run(V4, hm, hc)


def rows(path, header_prefix):
    out, on = [], False
    for line in open(path).read().splitlines():
        if line.startswith(header_prefix): on = True; continue
        if on and line.startswith("|---"): continue
        if on and line.startswith("|"): out.append(line)
        elif on and out: break
    return out


def tail_lines(path, prefix):
    return [l for l in open(path).read().splitlines() if l.startswith(prefix)]


